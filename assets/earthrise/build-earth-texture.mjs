// Builds earth-texture.js: the earthrise's invented Earth surface, generated from noise
// and packed. No page loads this script; they load its output, which saves generating
// the surface on every visit (about 8 ms on a desktop, most of a 65 ms task on a slow phone).
// Run it after changing anything here:
//   node assets/earthrise/build-earth-texture.mjs

export const TW = 128,
  TH = 64;

const hash = (x, y) => {
  let h = Math.imul(x | 0, 374761393) + Math.imul(y | 0, 668265263);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
};
const noise = (x, y, period) => {
  const xi = Math.floor(x),
    yi = Math.floor(y);
  const fx = x - xi,
    fy = y - yi;
  const u = fx * fx * (3 - 2 * fx),
    v = fy * fy * (3 - 2 * fy);
  const x0 = ((xi % period) + period) % period,
    x1 = (x0 + 1) % period;
  const a = hash(x0, yi),
    b = hash(x1, yi),
    c = hash(x0, yi + 1),
    d = hash(x1, yi + 1);
  return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
};
const fbm = (x, y, octaves, period) => {
  let s = 0,
    n = 0,
    amp = 0.5,
    f = 1;
  for (let i = 0; i < octaves; i++) {
    s += amp * noise(x * f, y * f, period * f);
    n += amp;
    amp *= 0.5;
    f *= 2;
  }
  return s / n;
};

// Each texel: 0 sea, 1 land, 2 cloud or ice. About three tenths land, a fifth cloud.
export function generate() {
  const l = new Float32Array(TW * TH),
    c = new Float32Array(TW * TH),
    ice = new Uint8Array(TW * TH);
  for (let j = 0; j < TH; j++) {
    const v = (j + 0.5) / TH,
      lat = Math.abs(0.5 - v) * 2;
    for (let i = 0; i < TW; i++) {
      const u = i / TW,
        t = j * TW + i;
      const warp = fbm(u * 4, v * 2 + 9, 3, 4);
      l[t] = fbm(u * 6 + 1.4 * warp, v * 3, 4, 6);
      c[t] = fbm(u * 10 + 2 * warp, v * 6 + 3, 4, 10);
      ice[t] = lat + 0.08 * fbm(u * 12, v * 6, 2, 12) > 0.91 ? 1 : 0;
    }
  }
  const quantile = (A, q) => Float32Array.from(A).sort()[Math.floor(q * (A.length - 1))];
  const shore = quantile(l, 0.7),
    cloudy = quantile(c, 0.78);
  const state = new Uint8Array(TW * TH);
  for (let t = 0; t < state.length; t++) state[t] = c[t] > cloudy || ice[t] ? 2 : l[t] > shore ? 1 : 0;
  return state;
}

// four texels to a byte, low bits first, as base64
export function pack(state) {
  const bytes = new Uint8Array(state.length / 4);
  for (let t = 0; t < state.length; t++) bytes[t >> 2] |= state[t] << ((t & 3) * 2);
  return Buffer.from(bytes).toString("base64");
}

const MODULE = (packed) => `// Generated by build-earth-texture.mjs; edit that and rerun it rather than this file.
// The earthrise's Earth: an invented globe, ${TW} x ${TH} texels wrapping in longitude.
// Each texel is 0 sea, 1 land or 2 cloud or ice, four to a byte.

const TW = ${TW},
  TH = ${TH};
const PACKED = "${packed}";

export const EARTH = (() => {
  const bytes = Uint8Array.from(atob(PACKED), (ch) => ch.charCodeAt(0));
  const state = new Uint8Array(TW * TH);
  for (let t = 0; t < state.length; t++) state[t] = (bytes[t >> 2] >> ((t & 3) * 2)) & 3;
  return state;
})();

// the texel at longitude u (in turns, wrapping) and v from the north pole (0) to the south (1)
export const sampleEarth = (u, v) =>
  EARTH[Math.min(TH - 1, Math.max(0, (v * TH) | 0)) * TW + (((((u % 1) + 1) % 1) * TW) | 0)];
`;

if (typeof process !== "undefined" && import.meta.url === `file://${process.argv[1]}`) {
  const { writeFileSync } = await import("node:fs");
  writeFileSync(new URL("./earth-texture.js", import.meta.url), MODULE(pack(generate())));
  console.log("wrote earth-texture.js");
}
